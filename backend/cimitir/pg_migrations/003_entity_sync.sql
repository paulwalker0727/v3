-- 003_entity_sync.sql — Etapa 6: sincronizare bidirecțională desktop (SQLite) <-> server (PostgreSQL) pe entități.
--
--  * version     : versiune optimistă per rând, crescută de trigger la ORICE modificare (inclusiv din panoul web).
--                  Clientul trimite `base_version` (ultima versiune cunoscută); dacă diferă de cea de pe server => conflict.
--  * change_seq  : număr monoton (secvență) atribuit la fiecare INSERT/UPDATE; clientul citește incremental `change_seq > cursor`.
--  * sync_tombstones : ștergerile (entitate + uid + versiune + change_seq), ca să ajungă și la ceilalți clienți.
--  * sync_conflicts  : conflictele detectate de server (nu se suprascrie nimic în tăcere); se raportează operatorului.
--  * sync_ops.response : răspunsul memorat pentru op_id => reluările sunt idempotente (același răspuns, fără re-aplicare).
-- Repetabilă (IF NOT EXISTS / OR REPLACE).

CREATE SEQUENCE IF NOT EXISTS sync_change_seq;

CREATE OR REPLACE FUNCTION cimitir_sync_touch() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.version = GREATEST(COALESCE(NEW.version, 0), 0) + 1;
    ELSE
        NEW.version = COALESCE(OLD.version, 0) + 1;
    END IF;
    NEW.modified_at = now();
    NEW.change_seq = nextval('sync_change_seq');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS sync_tombstones (
    entity      TEXT NOT NULL,
    uid         TEXT NOT NULL,
    version     INTEGER NOT NULL,
    change_seq  BIGINT NOT NULL,
    deleted_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (entity, uid)
);
CREATE INDEX IF NOT EXISTS idx_tombstones_seq ON sync_tombstones(entity, change_seq);

CREATE OR REPLACE FUNCTION cimitir_sync_tombstone() RETURNS trigger AS $$
BEGIN
    INSERT INTO sync_tombstones (entity, uid, version, change_seq)
    VALUES (TG_TABLE_NAME, OLD.uid, COALESCE(OLD.version, 0) + 1, nextval('sync_change_seq'))
    ON CONFLICT (entity, uid) DO UPDATE SET version = EXCLUDED.version, change_seq = EXCLUDED.change_seq, deleted_at = now();
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['locuri_de_veci', 'concesionari', 'contracte', 'inhumati', 'plati'] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS version INTEGER NOT NULL DEFAULT 0', t);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS change_seq BIGINT', t);
        -- rândurile existente primesc versiune 1 și un change_seq (ca să fie descărcate de clienți)
        EXECUTE format('UPDATE %I SET version = 1, change_seq = nextval(''sync_change_seq'') WHERE change_seq IS NULL', t);
        EXECUTE format('CREATE INDEX IF NOT EXISTS idx_%1$s_change_seq ON %1$I(change_seq)', t);
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_sync_touch ON %1$I', t);
        EXECUTE format('CREATE TRIGGER trg_%1$s_sync_touch BEFORE INSERT OR UPDATE ON %1$I FOR EACH ROW EXECUTE FUNCTION cimitir_sync_touch()', t);
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_sync_tomb ON %1$I', t);
        EXECUTE format('CREATE TRIGGER trg_%1$s_sync_tomb AFTER DELETE ON %1$I FOR EACH ROW EXECUTE FUNCTION cimitir_sync_tombstone()', t);
    END LOOP;
END $$;

