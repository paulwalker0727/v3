CREATE TABLE IF NOT EXISTS sync_conflicts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    op_id          TEXT NOT NULL UNIQUE,
    entity         TEXT NOT NULL,
    uid            TEXT NOT NULL,
    action         TEXT NOT NULL,
    reason         TEXT NOT NULL,               -- version_mismatch | already_exists | deleted_on_server | natural_key
    client_id      TEXT,
    base_version   INTEGER,
    server_version INTEGER,
    client_data    TEXT,      -- JSON (text: fără coloane JSONB noi față de scriptul de migrare)
    server_data    TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at    TIMESTAMPTZ,
    resolution     TEXT
);
CREATE INDEX IF NOT EXISTS idx_sync_conflicts_open ON sync_conflicts(resolved_at) WHERE resolved_at IS NULL;

