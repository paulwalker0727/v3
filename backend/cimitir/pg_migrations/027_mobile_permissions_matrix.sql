-- 027_mobile_permissions_matrix.sql — Permisiuni Mobile pe categorii (Vede/Adaugă/Editează/Șterge), câmpuri editabile, profiluri,
-- ștergere de pe telefon autorizată separat, jurnal de audit, istoric documente emise și numerotare chitanțe/avize.
--
-- ADITIVĂ și idempotentă. NU creează un sistem paralel: matricea se stochează în `sync_v2_permissions` (022), cu rânduri `perm:<categorie>:<acțiune>`,
-- `fields:<categorie>` (+ coloana nouă `detail` JSONB cu lista câmpurilor editabile) și `profile:<cheie>`.
-- Nu șterge/modifică date existente. Rollback: pg_rollbacks/027_mobile_permissions_matrix_ROLLBACK.sql (restaurează politica de DELETE din 022).
-- Rulați exclusiv pe TEST/dev, după verificarea project ref (scripts/apply_sync_v2_migration_test.py).

ALTER TABLE sync_v2_permissions ADD COLUMN IF NOT EXISTS detail JSONB;
GRANT UPDATE (detail) ON sync_v2_permissions TO cimitir_cp_app;

-- Profiluri personalizate (șabloane per cimitir). Cele 4 profiluri predefinite sunt în cod; aici se păstrează doar suprascrierile făcute din MAIN.
CREATE TABLE IF NOT EXISTS sync_v2_profiles (
    organization_uid UUID NOT NULL,
    cemetery_uid     UUID NOT NULL,
    key              TEXT NOT NULL CHECK (key ~ '^[a-z0-9_]{2,40}$'),
    label            TEXT NOT NULL CHECK (length(label) BETWEEN 1 AND 80),
    matrix           JSONB NOT NULL,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (cemetery_uid, key)
);

-- Jurnal de audit: modificări de permisiuni (MAIN), ștergeri/anulări de pe telefon, operații refuzate.
CREATE TABLE IF NOT EXISTS sync_v2_audit (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_uid UUID NOT NULL,
    cemetery_uid     UUID NOT NULL,
    binding_uid      UUID NOT NULL,
    device_type      TEXT NOT NULL,
    kind             TEXT NOT NULL CHECK (kind IN ('permissions_changed','delete','denied','issued','profile_changed')),
    entity           TEXT,
    entity_uid       TEXT,
    detail           JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sync_v2_audit_cem ON sync_v2_audit (cemetery_uid, id DESC);

-- Documente emise de pe telefon/MAIN (contract, chitanță, aviz, adeverință): istoric + numerotare fără duplicate.
CREATE TABLE IF NOT EXISTS sync_v2_issued (
    organization_uid UUID NOT NULL,
    cemetery_uid     UUID NOT NULL,
    uid              TEXT NOT NULL,
    kind             TEXT NOT NULL CHECK (kind IN ('contract','chitanta','aviz','adeverinta_inhumare','adeverinta_concesiune')),
    entity           TEXT NOT NULL,
    entity_uid       TEXT NOT NULL,
    number           TEXT NOT NULL,
    issued_by_binding UUID NOT NULL,
    device_type      TEXT NOT NULL,
    snapshot         JSONB NOT NULL,
    pdf_sha256       TEXT NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (cemetery_uid, uid),
    UNIQUE (cemetery_uid, kind, number),
    UNIQUE (cemetery_uid, kind, entity, entity_uid)
);
CREATE TABLE IF NOT EXISTS sync_v2_counters (
    organization_uid UUID NOT NULL,
    cemetery_uid     UUID NOT NULL,
    series           TEXT NOT NULL,
    last_no          BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (cemetery_uid, series)
);

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['sync_v2_profiles','sync_v2_audit','sync_v2_issued','sync_v2_counters']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS cp_tenant ON %I', t);
        EXECUTE format('CREATE POLICY cp_tenant ON %I TO cimitir_cp_app USING (cp_org_ok(organization_uid) AND cp_cem_ok(cemetery_uid)) '
                       'WITH CHECK (cp_org_ok(organization_uid) AND cp_cem_ok(cemetery_uid))', t);
        EXECUTE format('REVOKE ALL ON %I FROM cimitir_cp_app', t);
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN EXECUTE format('REVOKE ALL ON %I FROM anon', t); END IF;
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN EXECUTE format('REVOKE ALL ON %I FROM authenticated', t); END IF;
    END LOOP;
END $$;
GRANT SELECT, INSERT ON sync_v2_profiles, sync_v2_audit, sync_v2_issued TO cimitir_cp_app;
GRANT UPDATE (label, matrix, updated_at) ON sync_v2_profiles TO cimitir_cp_app;
GRANT SELECT, INSERT ON sync_v2_counters TO cimitir_cp_app;
GRANT UPDATE (last_no) ON sync_v2_counters TO cimitir_cp_app;
GRANT USAGE ON SEQUENCE sync_v2_audit_id_seq TO cimitir_cp_app;
-- Permisiunile nu se șterg niciodată: la schimbare se rescriu rândurile (UPDATE can_edit); rândul `mode:matrix` activează matricea pentru telefon.

-- Ștergere de pe telefon: NU mai este refuzată de RLS, ci condiționată de o variabilă de sesiune setată de server DOAR după verificarea permisiunii
-- „Șterge/Anulează" a categoriei (matricea de permisiuni din MAIN). Fără variabilă, comportamentul rămâne cel din 022 (doar MAIN).
CREATE OR REPLACE FUNCTION cp_mobile_delete_ok() RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT COALESCE(current_setting('cp.mobile_del', true), '') = '1' $$;
GRANT EXECUTE ON FUNCTION cp_mobile_delete_ok() TO cimitir_cp_app;
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['locuri_de_veci','concesionari','contracte','inhumati','plati','amenajari_avize']
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS sync_v2_delete ON %I', t);
        EXECUTE format('CREATE POLICY sync_v2_delete ON %I FOR DELETE TO cimitir_cp_app USING (organization_uid = cp_org() AND cp_cem_ok(cemetery_uid) '
                       'AND (cp_device_is_main() OR cp_mobile_delete_ok()))', t);
    END LOOP;
END $$;

-- Imaginea hărții (fundalul poligoanelor) din MAIN, pentru Mobile. Stocare privată (în DB, doar prin API cu permisiunea „Vede hartă"); max 8 MB; integritate prin sha256.
CREATE TABLE IF NOT EXISTS sync_v2_map_background (
    cemetery_uid     UUID PRIMARY KEY,
    organization_uid UUID NOT NULL,
    mime             TEXT NOT NULL CHECK (mime IN ('image/png','image/jpeg','image/webp')),
    width            INTEGER NOT NULL DEFAULT 0,
    height           INTEGER NOT NULL DEFAULT 0,
    sha256           TEXT NOT NULL,
    version          INTEGER NOT NULL DEFAULT 1,
    data             BYTEA NOT NULL CHECK (octet_length(data) <= 8388608),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE sync_v2_map_background ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS cp_tenant ON sync_v2_map_background;
CREATE POLICY cp_tenant ON sync_v2_map_background TO cimitir_cp_app USING (cp_org_ok(organization_uid) AND cp_cem_ok(cemetery_uid)) WITH CHECK (cp_org_ok(organization_uid) AND cp_cem_ok(cemetery_uid));
REVOKE ALL ON sync_v2_map_background FROM cimitir_cp_app;
GRANT SELECT, INSERT ON sync_v2_map_background TO cimitir_cp_app;
GRANT UPDATE (mime, width, height, sha256, version, data, updated_at) ON sync_v2_map_background TO cimitir_cp_app;
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN REVOKE ALL ON sync_v2_map_background FROM anon; END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN REVOKE ALL ON sync_v2_map_background FROM authenticated; END IF;
END $$;
