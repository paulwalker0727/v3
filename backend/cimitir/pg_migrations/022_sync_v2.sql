-- 022_sync_v2.sql — Sync v2 MAIN <-> Cloud TEST <-> Mobile: scriere autorizată în registrele live, jurnal, conflicte, permisiuni per telefon.
--
-- DREPTURI MINIME (rolul runtime rămâne cimitir_cp_app, fără BYPASSRLS; tenantul vine DOAR din binding: cp.org / cp.cems):
--   * INSERT / UPDATE pe registre: DOAR pe coloanele de date ale entității (listă explicită). Fără drept pe id, version, change_seq, modified_at;
--     UPDATE nu poate schimba uid / organization_uid / cemetery_uid.
--   * DELETE pe registre: permis de RLS numai dacă dispozitivul autentificat este MAIN (cp.device_type='MAIN', setat de server din binding).
--   * Triggerele de versiune/tombstone devin SECURITY DEFINER (search_path fixat): cimitir_cp_app NU primește INSERT/UPDATE pe sync_tombstones
--     și NU primește USAGE pe sync_change_seq.
--   * Tabelele de jurnal: INSERT/SELECT; UPDATE doar pe coloanele de rezolvare. Fără DELETE.
-- ROLLBACK VERIFIABIL: starea de dinainte (politici RLS, drepturi pe tabele/coloane/secvențe, definițiile funcțiilor) este salvată în
--   sync_v2_migration_backup împreună cu o amprentă (cimitir_sync_v2_fingerprint()); 022_sync_v2_ROLLBACK.sql o restaurează și REFUZĂ (ROLLBACK) dacă
--   amprenta de după nu este identică cu cea de dinainte.
-- Aditivă și idempotentă (a doua rulare nu suprascrie backup-ul). Nu șterge/modifică date. Rulați exclusiv pe TEST, după verificarea project ref.

CREATE OR REPLACE FUNCTION cimitir_sync_v2_fingerprint() RETURNS text LANGUAGE plpgsql STABLE AS $f$
DECLARE r oid; res text;
BEGIN
    SELECT oid INTO r FROM pg_roles WHERE rolname = 'cimitir_cp_app';
    SELECT md5(COALESCE(string_agg(x, E'\n' ORDER BY x), '')) INTO res FROM (
        SELECT 'policy|' || c.relname || '|' || p.polname || '|' || p.polcmd::text || '|' || p.polpermissive || '|' ||
               array_to_string(ARRAY(SELECT CASE WHEN o = 0 THEN 'public' ELSE (SELECT rolname FROM pg_roles WHERE oid = o) END FROM unnest(p.polroles) o ORDER BY 1), ',') || '|' ||
               COALESCE(pg_get_expr(p.polqual, p.polrelid), '') || '|' || COALESCE(pg_get_expr(p.polwithcheck, p.polrelid), '') AS x
          FROM pg_policy p JOIN pg_class c ON c.oid = p.polrelid
         WHERE c.relnamespace = current_schema()::regnamespace
           AND c.relname IN ('locuri_de_veci','concesionari','contracte','inhumati','plati','amenajari_avize','sectoare','sync_tombstones')
        UNION ALL
        SELECT 'rls|' || c.relname || '|' || c.relrowsecurity FROM pg_class c
         WHERE c.relnamespace = current_schema()::regnamespace
           AND c.relname IN ('locuri_de_veci','concesionari','contracte','inhumati','plati','amenajari_avize','sectoare','sync_tombstones')
        UNION ALL
        SELECT 'tacl|' || c.relname || '|' || a.privilege_type FROM pg_class c, LATERAL aclexplode(c.relacl) a
         WHERE c.relnamespace = current_schema()::regnamespace AND a.grantee = r
           AND c.relname IN ('locuri_de_veci','concesionari','contracte','inhumati','plati','amenajari_avize','sectoare','sync_tombstones')
        UNION ALL
        SELECT 'cacl|' || c.relname || '|' || t.attname || '|' || a.privilege_type
          FROM pg_class c JOIN pg_attribute t ON t.attrelid = c.oid AND t.attacl IS NOT NULL, LATERAL aclexplode(t.attacl) a
         WHERE c.relnamespace = current_schema()::regnamespace AND a.grantee = r
           AND c.relname IN ('locuri_de_veci','concesionari','contracte','inhumati','plati','amenajari_avize','sectoare','sync_tombstones')
        UNION ALL
        SELECT 'sacl|' || c.relname || '|' || a.privilege_type FROM pg_class c, LATERAL aclexplode(c.relacl) a
         WHERE c.relnamespace = current_schema()::regnamespace AND c.relkind = 'S' AND a.grantee = r
           AND (c.relname = 'sync_change_seq' OR c.relname IN ('locuri_de_veci_id_seq','concesionari_id_seq','contracte_id_seq','inhumati_id_seq','plati_id_seq','amenajari_avize_id_seq'))
        UNION ALL
        SELECT 'fn|' || p.proname || '|' || md5(pg_get_functiondef(p.oid)) FROM pg_proc p
         WHERE p.pronamespace = current_schema()::regnamespace AND p.proname IN ('cimitir_sync_touch','cimitir_sync_tombstone')
    ) q;
    RETURN res;
END
$f$;

CREATE TABLE IF NOT EXISTS sync_v2_migration_backup (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch       TEXT NOT NULL,
    ord         INTEGER NOT NULL,
    kind        TEXT NOT NULL,         -- function | rls | policy | grant | sequence | fingerprint
    object_name TEXT NOT NULL,
    restore_sql TEXT NOT NULL,
    taken_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

DO $$
DECLARE r oid;
        scope text[] := ARRAY['locuri_de_veci','concesionari','contracte','inhumati','plati','amenajari_avize','sectoare','sync_tombstones'];
BEGIN
    IF EXISTS (SELECT 1 FROM sync_v2_migration_backup WHERE batch = 'pre-022') THEN RETURN; END IF;   -- backup-ul ORIGINAL nu se suprascrie niciodată
    SELECT oid INTO r FROM pg_roles WHERE rolname = 'cimitir_cp_app';
    INSERT INTO sync_v2_migration_backup (batch, ord, kind, object_name, restore_sql)
    SELECT 'pre-022', 1, 'function', p.proname, pg_get_functiondef(p.oid) FROM pg_proc p
     WHERE p.pronamespace = current_schema()::regnamespace AND p.proname IN ('cimitir_sync_touch','cimitir_sync_tombstone');
    INSERT INTO sync_v2_migration_backup (batch, ord, kind, object_name, restore_sql)
    SELECT 'pre-022', 2, 'rls', c.relname, format('ALTER TABLE %I %s ROW LEVEL SECURITY', c.relname, CASE WHEN c.relrowsecurity THEN 'ENABLE' ELSE 'DISABLE' END)
      FROM pg_class c WHERE c.relnamespace = current_schema()::regnamespace AND c.relname = ANY (scope);
    INSERT INTO sync_v2_migration_backup (batch, ord, kind, object_name, restore_sql)
    SELECT 'pre-022', 3, 'policy', c.relname || '.' || p.polname,
           format('CREATE POLICY %I ON %I AS %s FOR %s TO %s%s%s', p.polname, c.relname, CASE WHEN p.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
                  CASE p.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' ELSE 'ALL' END,
                  array_to_string(ARRAY(SELECT CASE WHEN o = 0 THEN 'PUBLIC' ELSE quote_ident((SELECT rolname FROM pg_roles WHERE oid = o)) END FROM unnest(p.polroles) o), ', '),
                  CASE WHEN p.polqual IS NULL THEN '' ELSE ' USING (' || pg_get_expr(p.polqual, p.polrelid) || ')' END,
                  CASE WHEN p.polwithcheck IS NULL THEN '' ELSE ' WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')' END)
      FROM pg_policy p JOIN pg_class c ON c.oid = p.polrelid
     WHERE c.relnamespace = current_schema()::regnamespace AND c.relname = ANY (scope)
       AND p.polname IN ('mobile_cp_read','mobile_cp_test_insert','sync_v2_insert','sync_v2_update','sync_v2_delete','sync_v2_tomb_read');
    INSERT INTO sync_v2_migration_backup (batch, ord, kind, object_name, restore_sql)
    SELECT 'pre-022', 4, 'grant', c.relname, format('GRANT %s ON %I TO cimitir_cp_app', a.privilege_type, c.relname)
      FROM pg_class c, LATERAL aclexplode(c.relacl) a WHERE c.relnamespace = current_schema()::regnamespace AND a.grantee = r AND c.relname = ANY (scope);
    INSERT INTO sync_v2_migration_backup (batch, ord, kind, object_name, restore_sql)
    SELECT 'pre-022', 4, 'grant', c.relname || '.' || t.attname, format('GRANT %s (%I) ON %I TO cimitir_cp_app', a.privilege_type, t.attname, c.relname)
      FROM pg_class c JOIN pg_attribute t ON t.attrelid = c.oid AND t.attacl IS NOT NULL, LATERAL aclexplode(t.attacl) a
     WHERE c.relnamespace = current_schema()::regnamespace AND a.grantee = r AND c.relname = ANY (scope);
    INSERT INTO sync_v2_migration_backup (batch, ord, kind, object_name, restore_sql)
    SELECT 'pre-022', 5, 'sequence', c.relname, format('GRANT %s ON SEQUENCE %I TO cimitir_cp_app', a.privilege_type, c.relname)
      FROM pg_class c, LATERAL aclexplode(c.relacl) a
     WHERE c.relnamespace = current_schema()::regnamespace AND c.relkind = 'S' AND a.grantee = r
       AND (c.relname = 'sync_change_seq' OR c.relname IN ('locuri_de_veci_id_seq','concesionari_id_seq','contracte_id_seq','inhumati_id_seq','plati_id_seq','amenajari_avize_id_seq'));
    INSERT INTO sync_v2_migration_backup (batch, ord, kind, object_name, restore_sql)
    VALUES ('pre-022', 9, 'fingerprint', 'cimitir_sync_v2_fingerprint', cimitir_sync_v2_fingerprint());
END $$;
REVOKE ALL ON sync_v2_migration_backup FROM PUBLIC;

CREATE TABLE IF NOT EXISTS sync_v2_ops (
    op_id            TEXT NOT NULL,
    organization_uid UUID NOT NULL,
    cemetery_uid     UUID NOT NULL,
    binding_uid      UUID NOT NULL,
    device_type      TEXT NOT NULL,
    entity           TEXT NOT NULL,
    entity_uid       TEXT NOT NULL,
    action           TEXT NOT NULL,
    base_version     INTEGER NOT NULL DEFAULT 0,
    status           TEXT NOT NULL CHECK (status IN ('applied','conflict','rejected')),
    new_version      INTEGER,
    reason           TEXT,
    response         JSONB NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (cemetery_uid, op_id)
);
CREATE INDEX IF NOT EXISTS idx_sync_v2_ops_entity ON sync_v2_ops (cemetery_uid, entity, entity_uid, created_at);

CREATE TABLE IF NOT EXISTS sync_v2_conflicts (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_uid   UUID NOT NULL,
    cemetery_uid       UUID NOT NULL,
    op_id              TEXT NOT NULL,
    entity             TEXT NOT NULL,
    entity_uid         TEXT NOT NULL,
    reason             TEXT NOT NULL,      -- version_mismatch | deleted_on_server | natural_key
    origin_binding_uid UUID NOT NULL,
    origin_device_type TEXT NOT NULL,
    base_version       INTEGER,
    server_version     INTEGER,
    incoming           JSONB,              -- ce a încercat clientul să scrie
    server             JSONB,              -- starea serverului înainte de decizie (la main_wins: datele suprascrise, recuperabile)
    resolution         TEXT NOT NULL DEFAULT 'open' CHECK (resolution IN ('open','main_wins','kept_main','accepted_incoming','restored_previous','reviewed')),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at        TIMESTAMPTZ,
    UNIQUE (cemetery_uid, op_id)
);
CREATE INDEX IF NOT EXISTS idx_sync_v2_conflicts_open ON sync_v2_conflicts (cemetery_uid, resolution);

CREATE TABLE IF NOT EXISTS sync_v2_permissions (
    organization_uid UUID NOT NULL,
    cemetery_uid     UUID NOT NULL,
    binding_uid      UUID NOT NULL,
    entity           TEXT NOT NULL,
    can_edit         BOOLEAN NOT NULL DEFAULT false,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (binding_uid, entity)
);

CREATE TABLE IF NOT EXISTS sync_v2_runs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_uid UUID NOT NULL,
    cemetery_uid     UUID NOT NULL,
    binding_uid      UUID NOT NULL,
    device_type      TEXT NOT NULL,
    direction        TEXT NOT NULL CHECK (direction IN ('push','pull')),
    received         INTEGER NOT NULL DEFAULT 0,
    applied          INTEGER NOT NULL DEFAULT 0,
    conflicts        INTEGER NOT NULL DEFAULT 0,
    rejected         INTEGER NOT NULL DEFAULT 0,
    retries          INTEGER NOT NULL DEFAULT 0,
    duplicates       INTEGER NOT NULL DEFAULT 0,
    pulled           INTEGER NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sync_v2_runs_cem ON sync_v2_runs (cemetery_uid, id DESC);

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['sync_v2_ops','sync_v2_conflicts','sync_v2_permissions','sync_v2_runs']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS cp_tenant ON %I', t);
        EXECUTE format('CREATE POLICY cp_tenant ON %I TO cimitir_cp_app USING (cp_org_ok(organization_uid) AND cp_cem_ok(cemetery_uid)) '
                       'WITH CHECK (cp_org_ok(organization_uid) AND cp_cem_ok(cemetery_uid))', t);
        EXECUTE format('REVOKE ALL ON %I FROM cimitir_cp_app', t);
    END LOOP;
END $$;
GRANT SELECT, INSERT ON sync_v2_ops, sync_v2_runs TO cimitir_cp_app;
GRANT SELECT, INSERT ON sync_v2_conflicts TO cimitir_cp_app;
GRANT UPDATE (reason, resolution, resolved_at) ON sync_v2_conflicts TO cimitir_cp_app;
GRANT SELECT, INSERT ON sync_v2_permissions TO cimitir_cp_app;
GRANT UPDATE (can_edit, updated_at) ON sync_v2_permissions TO cimitir_cp_app;
GRANT USAGE ON SEQUENCE sync_v2_conflicts_id_seq, sync_v2_runs_id_seq TO cimitir_cp_app;

CREATE OR REPLACE FUNCTION cp_device_is_main() RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT COALESCE(current_setting('cp.device_type', true), '') = 'MAIN' $$;
GRANT EXECUTE ON FUNCTION cp_device_is_main() TO cimitir_cp_app;

DO $$
BEGIN
    EXECUTE format('ALTER FUNCTION cimitir_sync_touch() SECURITY DEFINER SET search_path = %I, pg_temp', current_schema());
    EXECUTE format('ALTER FUNCTION cimitir_sync_tombstone() SECURITY DEFINER SET search_path = %I, pg_temp', current_schema());
    EXECUTE 'REVOKE ALL ON FUNCTION cimitir_sync_touch(), cimitir_sync_tombstone() FROM PUBLIC';
END $$;
REVOKE INSERT, UPDATE, DELETE ON sync_tombstones FROM cimitir_cp_app;
REVOKE ALL ON SEQUENCE sync_change_seq FROM cimitir_cp_app;
GRANT SELECT ON sync_tombstones TO cimitir_cp_app;
ALTER TABLE sync_tombstones ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS sync_v2_tomb_read ON sync_tombstones;
CREATE POLICY sync_v2_tomb_read ON sync_tombstones FOR SELECT TO cimitir_cp_app USING (cp_org_ok(organization_uid) AND cp_cem_ok(cemetery_uid));

DO $$
DECLARE
    cfg constant jsonb := '{
      "locuri_de_veci": ["cod_loc","points","color","sector","parcela","rand","numar","capacitate","disponibilitate","tip","stare","categorie","suprafata","nr_vechi","numar_cf","ocupat","observatii","extra_data","are_inhumari"],
      "concesionari":   ["nume","prenume","cnp","bi_ci","adresa","telefon","email","observatii"],
      "contracte":      ["numar_contract","data_contract","data_inceput","data_sfarsit","cod_loc","valabilitate","observatii","extra_data","owner_fullname","owner_fullname_2","owner_address","owner_id_card_serie_number","owner_cnp","owner_phone","owner_email","cemetery_parcel","cemetery_row","cemetery_tomb","tomb_surface_m2","sector","concesionar_id","id_loc"],
      "inhumati":       ["nume","prenume","cnp","data_nasterii","data_deces","data_inhumare","data_deshumare","sex","cauza_deces","profesie","religie","ultima_adresa","observatii","nr_certificat_deces","nr_adeverinta_inhumare","id_loc","contract_id"],
      "plati":          ["cod_loc","suma","data_plata","tip","chitanta_nr","observatii","created_at","contract_id"],
      "amenajari_avize":["cod_loc","nr_aviz","data_aviz","lucrare","created_at"]
    }'::jsonb;
    t text; cols text; seq text;
BEGIN
    FOR t IN SELECT jsonb_object_keys(cfg) LOOP
        IF to_regclass(t) IS NULL THEN CONTINUE; END IF;
        SELECT string_agg(quote_ident(x), ', ') INTO cols FROM jsonb_array_elements_text(cfg -> t) x;
        EXECUTE format('REVOKE INSERT, UPDATE, DELETE ON %I FROM cimitir_cp_app', t);
        EXECUTE format('GRANT SELECT, DELETE ON %I TO cimitir_cp_app', t);
        EXECUTE format('GRANT INSERT (uid, organization_uid, cemetery_uid, %s) ON %I TO cimitir_cp_app', cols, t);
        EXECUTE format('GRANT UPDATE (%s) ON %I TO cimitir_cp_app', cols, t);
        seq := pg_get_serial_sequence(t, 'id');
        IF seq IS NOT NULL THEN EXECUTE format('GRANT USAGE ON SEQUENCE %s TO cimitir_cp_app', seq); END IF;
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS mobile_cp_read ON %I', t);
        EXECUTE format('CREATE POLICY mobile_cp_read ON %I FOR SELECT TO cimitir_cp_app USING (organization_uid = cp_org() AND cp_cem_ok(cemetery_uid))', t);
        EXECUTE format('DROP POLICY IF EXISTS mobile_cp_test_insert ON %I', t);
        EXECUTE format('DROP POLICY IF EXISTS sync_v2_insert ON %I', t);
        EXECUTE format('CREATE POLICY sync_v2_insert ON %I FOR INSERT TO cimitir_cp_app WITH CHECK (organization_uid = cp_org() AND cp_cem_ok(cemetery_uid))', t);
        EXECUTE format('DROP POLICY IF EXISTS sync_v2_update ON %I', t);
        EXECUTE format('CREATE POLICY sync_v2_update ON %I FOR UPDATE TO cimitir_cp_app USING (organization_uid = cp_org() AND cp_cem_ok(cemetery_uid)) '
                       'WITH CHECK (organization_uid = cp_org() AND cp_cem_ok(cemetery_uid))', t);
        EXECUTE format('DROP POLICY IF EXISTS sync_v2_delete ON %I', t);
        EXECUTE format('CREATE POLICY sync_v2_delete ON %I FOR DELETE TO cimitir_cp_app USING (organization_uid = cp_org() AND cp_cem_ok(cemetery_uid) AND cp_device_is_main())', t);
    END LOOP;
END $$;

-- sectoare: MAIN -> cloud (upsert pe (cimitir, id); fără DELETE; id = eticheta sectorului, fără uid/version în acest registru)
DO $$
BEGIN
    IF to_regclass('sectoare') IS NOT NULL THEN
        REVOKE INSERT, UPDATE, DELETE ON sectoare FROM cimitir_cp_app;
        GRANT SELECT ON sectoare TO cimitir_cp_app;
        GRANT INSERT (id, organization_uid, cemetery_uid, points, color) ON sectoare TO cimitir_cp_app;
        GRANT UPDATE (points, color) ON sectoare TO cimitir_cp_app;
        ALTER TABLE sectoare ENABLE ROW LEVEL SECURITY;
        DROP POLICY IF EXISTS mobile_cp_read ON sectoare;
        CREATE POLICY mobile_cp_read ON sectoare FOR SELECT TO cimitir_cp_app USING (organization_uid = cp_org() AND cp_cem_ok(cemetery_uid));
        DROP POLICY IF EXISTS sync_v2_insert ON sectoare;
        CREATE POLICY sync_v2_insert ON sectoare FOR INSERT TO cimitir_cp_app WITH CHECK (organization_uid = cp_org() AND cp_cem_ok(cemetery_uid) AND cp_device_is_main());
        DROP POLICY IF EXISTS sync_v2_update ON sectoare;
        CREATE POLICY sync_v2_update ON sectoare FOR UPDATE TO cimitir_cp_app USING (organization_uid = cp_org() AND cp_cem_ok(cemetery_uid) AND cp_device_is_main())
            WITH CHECK (organization_uid = cp_org() AND cp_cem_ok(cemetery_uid) AND cp_device_is_main());
    END IF;
END $$;
