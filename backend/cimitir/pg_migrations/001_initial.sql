-- 001_initial.sql — schema PostgreSQL de la zero (derivată din schema SQLite din shared/cimitir_database.py).
--
-- Convenții:
--  * id            : cheie numerică internă (identity), păstrată pentru compatibilitate cu endpointurile existente.
--  * uid           : UUID stabil (text canonic, ex. 'a1b2…') pentru entitățile sincronizate desktop <-> server.
--                    TEXT (nu tipul uuid) ca să fie identic cu SQLite-ul din desktop și cu codul existent; fără CHECK
--                    de format: serverul nu trebuie să respingă niciodată un uid trimis de desktop.
--  * modified_at   : TIMESTAMPTZ actualizat automat de trigger la orice UPDATE (baza pentru sincronizarea incrementală).
--  * Date/ore de business (data_contract, data_inhumare, created_at ...) rămân TEXT, exact ca în aplicația actuală
--    (formate românești „dd.mm.yyyy”); doar metadatele de sincronizare folosesc TIMESTAMPTZ.
--  * Geometrii (points, baseline) : JSONB (fără PostGIS — nu există interogări spațiale). `extra_data` rămâne TEXT
--    (JSON opac; codul existent îl scrie uneori ca șir gol).

CREATE OR REPLACE FUNCTION cimitir_set_modified_at() RETURNS trigger AS $$
BEGIN
    NEW.modified_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Compatibilitate SQLite: group_concat(text) (separator ',') pentru interogările SQL existente.
CREATE OR REPLACE FUNCTION cimitir_concat_step(state text, v text) RETURNS text AS $$
    SELECT CASE WHEN state IS NULL THEN v WHEN v IS NULL THEN state ELSE state || ',' || v END
$$ LANGUAGE sql IMMUTABLE;
DROP AGGREGATE IF EXISTS group_concat(text);
CREATE AGGREGATE group_concat(text) (SFUNC = cimitir_concat_step, STYPE = text);

