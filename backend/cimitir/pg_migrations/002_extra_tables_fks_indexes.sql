-- 002_extra_tables_fks_indexes.sql — completează schema PostgreSQL (Etapa 3). Repetabilă: poate rula peste 001 deja aplicată.
--
--  1. Tabele suplimentare existente în SQLite (create „lazy” de desktop): ai_scan_history, qr_generations, cloud_sync_*.
--     (cloud_sync_* sunt evidențe locale ale clientului desktop; se păstrează pentru paritate, Etapa ulterioară le va retrage.)
--  2. created_ts (TIMESTAMPTZ) pe toate tabelele care nu aveau moment de creare; modified_at + trigger pe tabelele noi.
--  3. Chei străine lipsă în SQLite dar logice: plati.contract_id, cereri_concesionare.contract_id, qr_generations.loc_id.
--     NU se pun FK pe plati.cod_loc / contracte.cod_loc / cereri.cod_loc: sunt copii istorice (plățile și contractele supraviețuiesc
--     ștergerii locului), iar `documents` e polimorfică (entity_type + entity_id) — orfanii se raportează la migrare.
--  4. Indexuri pentru căutările și filtrele folosite de aplicație.
--  Nu se adaugă CHECK-uri pe date de business (ar respinge date vechi legitime). ID-urile sunt IDENTITY BY DEFAULT: acceptă id
--  explicit (migrarea le păstrează), iar `cimitir_reset_sequences()` aliniază secvențele după import.

-- ---------------------------------------------------------------- tabele suplimentare
CREATE TABLE IF NOT EXISTS ai_scan_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid            TEXT NOT NULL DEFAULT gen_random_uuid()::text UNIQUE,
    created_at     TEXT NOT NULL,
    document_type  TEXT NOT NULL,
    filename       TEXT,
    file_path      TEXT,
    status         TEXT NOT NULL DEFAULT 'processed',
    entity_type    TEXT,
    entity_id      BIGINT,
    extracted_json TEXT,
    modified_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS qr_generations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid          TEXT NOT NULL DEFAULT gen_random_uuid()::text UNIQUE,
    loc_id       BIGINT,
    cod_loc      TEXT NOT NULL,
    generated_at TEXT NOT NULL,
    generated_by TEXT,
    format       TEXT NOT NULL,
    path         TEXT,
    printed_at   TEXT,
    printed_by   TEXT,
    notes        TEXT,
    modified_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS cloud_sync_map (
    tracking_code  TEXT PRIMARY KEY,
    cerere_id      BIGINT,
    pushed_status  TEXT DEFAULT '',
    imported_at    TEXT,
    pushed_version INTEGER DEFAULT 0,
    revision       INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS cloud_sync_outbox (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_code TEXT,
    status        TEXT,
    note          TEXT,
    created_at    TEXT,
    op_id         TEXT,
    kind          TEXT,
    payload       TEXT,
    attempts      INTEGER DEFAULT 0,
    last_error    TEXT
);

CREATE TABLE IF NOT EXISTS cloud_sync_docs (
    tracking_code TEXT NOT NULL,
    doc_id        BIGINT NOT NULL,
    PRIMARY KEY (tracking_code, doc_id)
);

-- ---------------------------------------------------------------- created_ts pe toate tabelele (unde lipsea)
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['locuri_de_veci','concesionari','contracte','inhumati','sectoare','settings','photos',
                             'amenajari_avize','loc_extra','guides','rows_ghid','plati','documents','citizens',
                             'cereri_concesionare','users','ai_scan_history','qr_generations',
                             'audit_log','loc_holders','sync_ops','citizen_resets','email_outbox',
                             'cloud_sync_map','cloud_sync_outbox','cloud_sync_docs']
    LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS created_ts TIMESTAMPTZ NOT NULL DEFAULT now()', t);
    END LOOP;
    -- triggerul modified_at și pe tabelele noi cu această coloană
    FOREACH t IN ARRAY ARRAY['ai_scan_history','qr_generations']
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_modified ON %1$I', t);
        EXECUTE format('CREATE TRIGGER trg_%1$s_modified BEFORE UPDATE ON %1$I FOR EACH ROW EXECUTE FUNCTION cimitir_set_modified_at()', t);
    END LOOP;
END $$;

-- ---------------------------------------------------------------- chei străine (repetabil: doar dacă lipsesc)
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_plati_contract') THEN
        ALTER TABLE plati ADD CONSTRAINT fk_plati_contract
            FOREIGN KEY (contract_id) REFERENCES contracte(id) ON DELETE SET NULL ON UPDATE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_cereri_contract') THEN
        ALTER TABLE cereri_concesionare ADD CONSTRAINT fk_cereri_contract
            FOREIGN KEY (contract_id) REFERENCES contracte(id) ON DELETE SET NULL ON UPDATE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_qr_loc') THEN
        ALTER TABLE qr_generations ADD CONSTRAINT fk_qr_loc
            FOREIGN KEY (loc_id) REFERENCES locuri_de_veci(id) ON DELETE SET NULL ON UPDATE CASCADE;
    END IF;
END $$;

